# A variable is a reusable name attached to a value. These examples show
# strings (text) and integers (whole numbers) assigned to descriptive names.
student_name = 'Excellence Oseobulu Oseagwina'
age = 25
department = 'Cyber Security'
math = 95
eng = 86
phys = 73
chem = 100

# print() can display values. The + operator joins strings, so numeric values
# such as age and scores are converted with str() before they are concatenated.
print("Student Name: " + student_name)
print("Student Age: " + str(age))
print("Student Department: " + department)

# Printing an empty string creates a blank line to separate the two sections.
print('') #For space

print("Mathematics: " + str(math))
print("English Language: " + str(eng))
print("Physics: " + str(phys))
print("Chemistry: " + str(chem))
