# LESSON GUIDE: A Boolean is a yes/no value used to represent a true or false
# fact. The two assignments below are data; the print() calls show those values.
# Boolean values represent one of two states: True or False.
# Python capitalizes these names, and they are values rather than strings:
# write True, not "True", when a condition needs a real Boolean.
is_graduate = True
is_first_class = False
# print() displays each value; it does not add quotation marks around Booleans.
print(is_graduate)
print(is_first_class)
